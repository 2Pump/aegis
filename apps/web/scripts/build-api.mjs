/**
 * Bundles api-src/v1.ts → api/v1.js: one self-contained ESM file for the Vercel Node runtime (no workspace
 * TypeScript left for Vercel to compile).
 *
 * `node scripts/build-api.mjs --check` fails if api/v1.js wasn't built from the current sources. It compares a
 * FINGERPRINT OF THE INPUTS (written into the bundle's first line), not the bundle's bytes: esbuild's output can differ
 * slightly between machines (Windows vs Linux, pnpm folder names), while the inputs are the same everywhere:
 *   - every AEGIS source file the bundle uses (line endings normalised)
 *   - pnpm-lock.yaml (= the exact library versions)
 *   - the esbuild version and the build options
 *   - the test-wallet list baked into it
 * `pnpm check` runs it, so a stale bundle can't be deployed by mistake.
 */
import { build, version as esbuildVersion } from 'esbuild';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '..');
const root = join(web, '..', '..');
const out = join(web, 'api', 'v1.js');
const MARK = '// aegis-api-inputs:';

// AEGIS's synthetic test wallets: baked in, so the function refuses them without reading the repo at runtime
const fixtures = new Set();
for (const f of readdirSync(join(root, 'fixtures')).filter((x) => x.endsWith('.json'))) for (const m of readFileSync(join(root, 'fixtures', f), 'utf8').matchAll(/0x[0-9a-fA-F]{40}\b/g)) fixtures.add(m[0].toLowerCase());
const fixtureList = [...fixtures].sort();

const OPTIONS = { bundle: true, platform: 'node', format: 'esm', target: 'node20', minify: false, legalComments: 'none', sourcemap: false };

const res = await build({
  ...OPTIONS,
  entryPoints: [join(web, 'api-src', 'v1.ts')],
  write: false,
  metafile: true,
  absWorkingDir: web,
  define: { __FIXTURES__: JSON.stringify(fixtureList) },
  logLevel: 'warning',
});

// the fingerprint: our own sources (not node_modules — the lockfile pins those), normalised, in a stable order
const norm = (s) => s.replace(/\r\n/g, '\n');
const ours = Object.keys(res.metafile.inputs)
  .filter((p) => !p.startsWith('<'))
  .map((p) => resolve(web, p))
  .filter((p) => !p.split(sep).includes('node_modules'))
  .map((p) => relative(root, p).split(sep).join('/'))
  .sort();
const h = createHash('sha256');
h.update(`esbuild ${esbuildVersion}\n${JSON.stringify(OPTIONS)}\n${JSON.stringify(fixtureList)}\n`);
h.update(norm(readFileSync(join(root, 'pnpm-lock.yaml'), 'utf8')));
for (const p of ours) h.update(`\n--- ${p}\n${norm(readFileSync(join(root, p), 'utf8'))}`);
const fingerprint = h.digest('hex').slice(0, 32);

if (process.argv.includes('--check')) {
  const first = existsSync(out) ? readFileSync(out, 'utf8').split(/\r?\n/, 1)[0] : '';
  const have = first.startsWith(MARK) ? first.slice(MARK.length).trim() : '(none)';
  if (have !== fingerprint) {
    console.error(`api/v1.js was not built from the current sources (bundle ${have}, sources ${fingerprint}, ${ours.length} files).`);
    console.error('Run `pnpm --filter @aegis/web build:api` and commit api/v1.js.');
    process.exit(1);
  }
  console.log(`api/v1.js is up to date (inputs ${fingerprint}, ${ours.length} source files)`);
} else {
  const header = `${MARK} ${fingerprint}\n// GENERATED by apps/web/scripts/build-api.mjs from api-src/ — do not edit.\nimport { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);\n`;
  writeFileSync(out, header + res.outputFiles[0].text);
  console.log(`api/v1.js written (${((header.length + res.outputFiles[0].text.length) / 1024).toFixed(0)} KB, inputs ${fingerprint}, ${ours.length} source files)`);
}
