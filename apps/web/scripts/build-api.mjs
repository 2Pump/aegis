/**
 * Bundles api-src/v1.ts → api/v1.js: one self-contained ESM file for the Vercel Node runtime (no workspace
 * TypeScript left for Vercel to compile). `node scripts/build-api.mjs --check` fails if api/v1.js is out of date —
 * `pnpm check` runs it, so a stale bundle can't be deployed by mistake.
 */
import { build } from 'esbuild';
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '..');
const root = join(web, '..', '..');
const out = join(web, 'api', 'v1.js');

// AEGIS's synthetic test wallets: baked in, so the function refuses them without reading the repo at runtime
const fixtures = new Set();
for (const f of readdirSync(join(root, 'fixtures')).filter((x) => x.endsWith('.json'))) for (const m of readFileSync(join(root, 'fixtures', f), 'utf8').matchAll(/0x[0-9a-fA-F]{40}\b/g)) fixtures.add(m[0].toLowerCase());

const res = await build({
  entryPoints: [join(web, 'api-src', 'v1.ts')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  write: false,
  minify: false,
  legalComments: 'none',
  sourcemap: false,
  define: { __FIXTURES__: JSON.stringify([...fixtures].sort()) },
  banner: { js: "// GENERATED by apps/web/scripts/build-api.mjs from api-src/ — do not edit.\nimport { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
  logLevel: 'warning',
});
const code = res.outputFiles[0].text;
if (process.argv.includes('--check')) {
  // compare ignoring line endings (git on Windows may check the file out with CRLF)
  // …and ignoring comment-only lines (esbuild writes source paths there, which can differ between machines)
  const norm = (x) => x.replace(/\r\n/g, '\n').split('\n').filter((l) => !/^\s*\/\//.test(l)).join('\n');
  const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (norm(cur) !== norm(code)) {
    console.error('api/v1.js is out of date — run `pnpm --filter @aegis/web build:api` and commit the result');
    process.exit(1);
  }
  console.log('api/v1.js is up to date');
} else {
  writeFileSync(out, code);
  console.log(`api/v1.js written (${(code.length / 1024).toFixed(0)} KB)`);
}
